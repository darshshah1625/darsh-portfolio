document.getElementById('startButton').addEventListener('click', async (e) => {
  const button = e.currentTarget;
  
  // Create ripple effect
  const ripple = document.createElement('div');
  ripple.style.cssText = `
    position: absolute;
    border-radius: 50%;
    background: rgba(255, 255, 255, 0.6);
    width: 20px;
    height: 20px;
    pointer-events: none;
    transform: translate(-50%, -50%);
    animation: ripple 0.6s ease-out;
  `;
  
  const rect = button.getBoundingClientRect();
  ripple.style.left = (e.clientX - rect.left) + 'px';
  ripple.style.top = (e.clientY - rect.top) + 'px';
  
  button.appendChild(ripple);
  
  // Add ripple animation
  const style = document.createElement('style');
  style.textContent = `
    @keyframes ripple {
      to {
        transform: translate(-50%, -50%) scale(20);
        opacity: 0;
      }
    }
  `;
  document.head.appendChild(style);
  
  setTimeout(() => ripple.remove(), 600);
  
  // Disable button
  button.disabled = true;
  button.style.opacity = '0.7';
  
  // Fade out start screen with scale effect
  const startScreen = document.getElementById('startScreen');
  startScreen.style.transition = 'opacity 0.8s ease-out, transform 0.8s ease-out';
  startScreen.style.opacity = '0';
  startScreen.style.transform = 'scale(1.1)';
  
  // Play sound after a brief moment
  setTimeout(() => {
    playTudum();
  }, 300);
  
  // Show intro after fade
  setTimeout(() => {
    startScreen.style.display = 'none';
    document.getElementById('intro').classList.add('active');
  }, 800);
  
  // After intro animation, show profile selection
  setTimeout(() => {
    document.getElementById('intro').style.display = 'none';
    document.getElementById('profileSelection').classList.add('active');
    initProfileBg();
  }, 4300);
});

