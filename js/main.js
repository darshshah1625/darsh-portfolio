// Particles animation for start screen - ENHANCED
function initParticles() {
  const canvas = document.getElementById('particlesCanvas');
  const ctx = canvas.getContext('2d');
  canvas.width = window.innerWidth;
  canvas.height = window.innerHeight;
  
  const particles = [];
  const particleCount = 150;
  
  // Create particles with varying properties
  for (let i = 0; i < particleCount; i++) {
    particles.push({
      x: Math.random() * canvas.width,
      y: Math.random() * canvas.height,
      vx: (Math.random() - 0.5) * 1,
      vy: (Math.random() - 0.5) * 1,
      size: Math.random() * 3 + 1,
      opacity: Math.random() * 0.5 + 0.2,
      hue: Math.random() * 20 // Red hues
    });
  }
  
  // Mouse interaction
  let mouse = { x: null, y: null, radius: 150 };
  
  canvas.addEventListener('mousemove', (e) => {
    mouse.x = e.x;
    mouse.y = e.y;
  });
  
  canvas.addEventListener('mouseleave', () => {
    mouse.x = null;
    mouse.y = null;
  });
  
  function animate() {
    // Fade effect
    ctx.fillStyle = 'rgba(0, 0, 0, 0.05)';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    
    particles.forEach((p, i) => {
      // Update position
      p.x += p.vx;
      p.y += p.vy;
      
      // Bounce off edges
      if (p.x < 0 || p.x > canvas.width) p.vx *= -1;
      if (p.y < 0 || p.y > canvas.height) p.vy *= -1;
      
      // Mouse interaction - repel particles
      if (mouse.x && mouse.y) {
        const dx = mouse.x - p.x;
        const dy = mouse.y - p.y;
        const distance = Math.sqrt(dx * dx + dy * dy);
        
        if (distance < mouse.radius) {
          const force = (mouse.radius - distance) / mouse.radius;
          const angle = Math.atan2(dy, dx);
          p.vx -= Math.cos(angle) * force * 0.5;
          p.vy -= Math.sin(angle) * force * 0.5;
        }
      }
      
      // Damping
      p.vx *= 0.99;
      p.vy *= 0.99;
      
      // Draw particle
      ctx.fillStyle = `hsla(${p.hue}, 100%, 50%, ${p.opacity})`;
      ctx.beginPath();
      ctx.arc(p.x, p.y, p.size, 0, Math.PI * 2);
      ctx.fill();
      
      // Draw connections
      particles.forEach((p2, j) => {
        if (i === j) return;
        const dx = p.x - p2.x;
        const dy = p.y - p2.y;
        const distance = Math.sqrt(dx * dx + dy * dy);
        
        if (distance < 100) {
          ctx.strokeStyle = `rgba(229, 9, 20, ${(1 - distance / 100) * 0.2})`;
          ctx.lineWidth = 0.5;
          ctx.beginPath();
          ctx.moveTo(p.x, p.y);
          ctx.lineTo(p2.x, p2.y);
          ctx.stroke();
        }
      });
    });
    
    requestAnimationFrame(animate);
  }
  animate();
  
  // Resize handler
  window.addEventListener('resize', () => {
    canvas.width = window.innerWidth;
    canvas.height = window.innerHeight;
  });
}

// Profile background animation
function initProfileBg() {
  const canvas = document.getElementById('profileBg');
  const ctx = canvas.getContext('2d');
  canvas.width = window.innerWidth;
  canvas.height = window.innerHeight;
  
  let time = 0;
  function animate() {
    ctx.fillStyle = 'rgba(20, 20, 20, 0.1)';
    ctx.fillRect(0, 0, canvas.width, canvas.height);
    
    for (let i = 0; i < 3; i++) {
      const x = canvas.width / 2 + Math.sin(time * 0.001 + i) * 200;
      const y = canvas.height / 2 + Math.cos(time * 0.001 + i) * 200;
      
      const gradient = ctx.createRadialGradient(x, y, 0, x, y, 200);
      gradient.addColorStop(0, 'rgba(229, 9, 20, 0.1)');
      gradient.addColorStop(1, 'transparent');
      
      ctx.fillStyle = gradient;
      ctx.fillRect(0, 0, canvas.width, canvas.height);
    }
    
    time++;
    requestAnimationFrame(animate);
  }
  animate();
}

// Netflix tudum sound - Using base64 encoded audio
function playTudum() {
  try {
    // Create a simple beep sound using data URI
    const audio = new Audio();
    
    // Generate a simple TUDUM sound effect
    const audioContext = new (window.AudioContext || window.webkitAudioContext)();
    const sampleRate = audioContext.sampleRate;
    const duration = 2;
    const numSamples = sampleRate * duration;
    const buffer = audioContext.createBuffer(1, numSamples, sampleRate);
    const data = buffer.getChannelData(0);
    
    // Generate TUDUM waveform
    for (let i = 0; i < numSamples; i++) {
      const t = i / sampleRate;
      let value = 0;
      
      // TU (first hit at 0.1s)
      if (t >= 0.1 && t < 0.9) {
        const env = Math.exp(-(t - 0.1) * 8);
        value += Math.sin(2 * Math.PI * 110 * (t - 0.1)) * env * 0.5;
      }
      
      // DUM (second hit at 0.5s)
      if (t >= 0.5 && t < 2.0) {
        const env = Math.exp(-(t - 0.5) * 3);
        value += Math.sin(2 * Math.PI * 82 * (t - 0.5)) * env * 0.7;
      }
      
      data[i] = value;
    }
    
    // Play the buffer
    const source = audioContext.createBufferSource();
    source.buffer = buffer;
    source.connect(audioContext.destination);
    source.start(0);
    
    console.log('🔊 TUDUM playing!');
    
  } catch (e) {
    console.error('❌ Audio error:', e);
    console.log('💡 Sound blocked by browser. User interaction detected but audio context may need permission.');
  }
}

